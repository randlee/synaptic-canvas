#!/usr/bin/env python3
"""Generate test-packages fixtures from plugin eval cases.

Source of truth stays `packages/<pkg>/evals/` (the `claude plugin eval` format:
prompt.md frontmatter + body, graders/*.md, scaffold.sh). This script converts
each case into a test-packages fixture so the runs execute under the harness —
isolated HOME, hook traces, artifact preservation, HTML reports:

    test-packages/fixtures/<pkg>-evals/
        fixture.yaml
        resources/<case>/scaffold.sh
        tests/test_<case>.yaml        # GENERATED — do not edit

Grader -> expectation mapping:
    regex (last_message, contains)      -> output_contains
    regex (last_message, not_contains)  -> output_not_contains
    regex ({source: file}, contains)    -> file_contains
    regex ({source: file}, not_contains)-> file_not_contains
    tool_used (min >= 1)                -> tool_call
    tool_used (max == 0)                -> tool_not_called
    tool_order                          -> tool_order
    llm                                 -> llm_judge

A case `env:` block (e.g. the stub-gh PATH) is applied by a generated setup
command that merges it into the test project's `.claude/settings.json` with
relative PATH entries absolutized — the harness runs Claude with
`--setting-sources project`, so the session picks it up.

Usage: python3 scripts/generate-eval-fixtures.py [--package NAME]
"""
from __future__ import annotations

import argparse
import importlib.util
import shutil
import sys
from pathlib import Path
from typing import Any, Dict, List

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
PACKAGES_DIR = REPO_ROOT / "packages"
FIXTURES_DIR = REPO_ROOT / "test-packages" / "fixtures"

_spec = importlib.util.spec_from_file_location(
    "run_evals_local", REPO_ROOT / "scripts" / "run-evals-local.py")
_rel = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_rel)
parse_front_matter = _rel.parse_front_matter

GENERATED_HEADER = (
    "# GENERATED by scripts/generate-eval-fixtures.py from packages/{pkg}/evals/{case}\n"
    "# Do not edit — change the eval case and re-run the generator.\n"
)


def _env_merge_command(env: Dict[str, Any]) -> str:
    """Setup command that merges the case env into .claude/settings.json,
    absolutizing relative PATH entries against the project root."""
    payload = {str(k): str(v) for k, v in env.items()}
    return (
        "python3 - <<'MERGE_ENV_EOF'\n"
        "import json, os, pathlib\n"
        f"case_env = {payload!r}\n"
        "p = pathlib.Path('.claude/settings.json')\n"
        "data = json.loads(p.read_text()) if p.exists() else {}\n"
        "env = data.setdefault('env', {})\n"
        "cwd = os.getcwd()\n"
        "for key, raw in case_env.items():\n"
        "    if key == 'PATH':\n"
        "        parts = []\n"
        "        for entry in raw.split(':'):\n"
        "            if entry.startswith('./') or entry.startswith('../'):\n"
        "                parts.append(os.path.normpath(os.path.join(cwd, entry)))\n"
        "            else:\n"
        "                parts.append(entry)\n"
        "        env[key] = ':'.join(parts)\n"
        "    else:\n"
        "        env[key] = raw\n"
        "p.parent.mkdir(parents=True, exist_ok=True)\n"
        "p.write_text(json.dumps(data, indent=2))\n"
        "MERGE_ENV_EOF"
    )


def _map_grader(name: str, g: Dict[str, Any]) -> Dict[str, Any]:
    gtype = g.get("type", "regex")
    desc = f"grader: {name}"
    if gtype == "regex":
        target = g.get("target", "last_message")
        contains = g.get("match", "contains") == "contains"
        if isinstance(target, dict) and target.get("source") == "file":
            etype = "file_contains" if contains else "file_not_contains"
            expected = {"path": target.get("path", ""), "pattern": g.get("pattern", ""),
                        "flags": g.get("flags", "")}
        else:
            etype = "output_contains" if contains else "output_not_contains"
            expected = {"pattern": g.get("pattern", ""), "flags": g.get("flags", "")}
        return {"description": desc, "type": etype, "expected": expected}
    if gtype == "tool_used":
        forbidden = g.get("max") == 0
        return {"description": desc,
                "type": "tool_not_called" if forbidden else "tool_call",
                "expected": {"tool": g.get("tool", "Bash"),
                             "pattern": g.get("input_match", ""), "flags": "i"}}
    if gtype == "tool_order":
        return {"description": desc, "type": "tool_order",
                "expected": {"before": g.get("before", ""), "after": g.get("after", "")}}
    if gtype == "llm":
        return {"description": desc, "type": "llm_judge",
                "expected": {"criteria": g.get("criteria", "")}}
    raise ValueError(f"unmapped grader type {gtype!r} in {name}")


def generate_package(pkg: str) -> List[Path]:
    evals_dir = PACKAGES_DIR / pkg / "evals"
    fixture_dir = FIXTURES_DIR / f"{pkg}-evals"
    written: List[Path] = []

    cases = [d for d in sorted(evals_dir.iterdir())
             if d.is_dir() and d.name != "results" and (d / "prompt.md").exists()]
    if not cases:
        return written

    (fixture_dir / "tests").mkdir(parents=True, exist_ok=True)
    fixture_yaml = fixture_dir / "fixture.yaml"
    fixture_yaml.write_text(
        f"# GENERATED by scripts/generate-eval-fixtures.py from packages/{pkg}/evals\n"
        "# Do not edit — change the eval cases and re-run the generator.\n"
        + yaml.safe_dump({
            "name": f"{pkg}-evals",
            "description": f"Field-incident evals for {pkg} "
                           f"(source: packages/{pkg}/evals, see its INCIDENTS.md)",
            "package": f"{pkg}@synaptic-canvas",
            "setup": {"plugins": [f"{pkg}@synaptic-canvas"]},
            "tests_dir": "tests",
        }, sort_keys=False), encoding="utf-8")
    written.append(fixture_yaml)

    for case_dir in cases:
        meta, prompt = parse_front_matter((case_dir / "prompt.md").read_text(encoding="utf-8"))
        setup: Dict[str, Any] = {}
        commands: List[str] = []
        files: List[Dict[str, str]] = []
        scaffold = case_dir / "scaffold.sh"
        if scaffold.exists():
            res = fixture_dir / "resources" / case_dir.name / "scaffold.sh"
            res.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(scaffold, res)
            written.append(res)
            files.append({"src": f"resources/{case_dir.name}/scaffold.sh",
                          "dest": "scaffold.sh"})
            # The harness project persists across cases — scrub prior
            # scaffold residue so fixtures never collide.
            commands.append("rm -rf ./repo ./origin.git ./bin ./gh-calls.log "
                            "./repo-worktrees ./wt-base ./.sc ./AGENTS.md "
                            "./.codex-zdot ./zdot")
            commands.append("bash scaffold.sh")
        if meta.get("env"):
            commands.append(_env_merge_command(meta["env"]))
        if files:
            setup["files"] = files
        if commands:
            setup["commands"] = commands

        expectations = []
        for i, gf in enumerate(sorted((case_dir / "graders").glob("*.md"))):
            gmeta, _ = parse_front_matter(gf.read_text(encoding="utf-8"))
            exp = _map_grader(gf.stem, gmeta)
            exp = {"id": f"exp-{i+1:03d}", **exp}
            expectations.append(exp)

        test_doc: Dict[str, Any] = {
            "test_id": f"{pkg}-eval-{case_dir.name}",
            "test_name": str(meta.get("name", case_dir.name)),
            "description": f"Generated from packages/{pkg}/evals/{case_dir.name} "
                           f"(background: packages/{pkg}/evals/INCIDENTS.md)",
            "tags": list(meta.get("tags", [])) + ["generated-eval"],
            "execution": {
                "prompt": prompt.strip(),
                "model": str(meta.get("model", "haiku")),
                "tools": list(meta.get("allowed_tools", [])),
                "timeout_ms": int(meta.get("timeout_seconds", 300)) * 1000,
            },
            "expectations": expectations,
        }
        if setup:
            test_doc["setup"] = setup
        out = fixture_dir / "tests" / f"test_{case_dir.name.replace('-', '_')}.yaml"
        out.write_text(GENERATED_HEADER.format(pkg=pkg, case=case_dir.name)
                       + yaml.safe_dump(test_doc, sort_keys=False, width=100),
                       encoding="utf-8")
        written.append(out)
    return written


def main(argv: List[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="generate harness fixtures from plugin evals")
    ap.add_argument("--package", help="only this package (default: every package with evals/)")
    args = ap.parse_args(argv)
    pkgs = [args.package] if args.package else [
        p.name for p in sorted(PACKAGES_DIR.iterdir()) if (p / "evals").is_dir()]
    total = []
    for pkg in pkgs:
        if not (PACKAGES_DIR / pkg / "evals").is_dir():
            print(f"error: no evals/ in packages/{pkg}", file=sys.stderr)
            return 1
        wrote = generate_package(pkg)
        total.extend(wrote)
        print(f"{pkg}: {len(wrote)} file(s)")
    for p in total:
        print(f"  {p.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
